/**
 * Output: one line per attack while the run goes, a summary, the structured JSON report, and the
 * Markdown report (`redteam/REPORT.md`). Every sentence of prose in the Markdown is on its own line.
 */
import { formatCents } from "@mandate/shared";
import type { AttackRecord, RunReport, RunSummary } from "./types";

const usd = formatCents;

export function summarize(records: readonly AttackRecord[]): RunSummary {
  const count = (verdict: AttackRecord["verdict"]) => records.filter((r) => r.verdict === verdict).length;
  return {
    held: count("held"),
    bounded: count("bounded"),
    breach: count("BREACH"),
    errors: count("ERROR"),
    skipped: count("SKIPPED"),
    unexpected: records.filter((r) => !r.asExpected).length,
  };
}

/** Whether a run passed: nothing breached, nothing errored, everything as expected, nothing aborted. */
export function passed(report: RunReport): boolean {
  const s = summarize(report.attacks);
  return report.aborted === null && s.breach === 0 && s.errors === 0 && s.unexpected === 0;
}

const shortHash = (hash: string) => `${hash.slice(0, 10)}...`;

/** One line for the terminal. */
export function line(r: AttackRecord): string {
  const tag = r.verdict === "SKIPPED" ? "skip" : r.verdict;
  const flag = r.asExpected ? "" : "  << UNEXPECTED (expected " + r.expectedVerdict + ")";
  const txs = r.txHashes.length === 0 ? "" : ` [tx ${r.txHashes.map(shortHash).join(", ")}]`;
  return `${`[${tag}]`.padEnd(10)}${r.surface.padEnd(6)}${r.id}: ${r.actual}${txs}${flag}`;
}

export function summaryLine(report: RunReport): string {
  const s = summarize(report.attacks);
  return (
    `${report.target === "self" ? `self-contained (${report.contract})` : `live stack (${report.contract})`}: ` +
    `${report.attacks.length} records, ${s.held} held, ${s.bounded} bounded, ${s.breach} BREACH, ` +
    `${s.errors} error, ${s.skipped} skipped, ${s.unexpected} unexpected` +
    (report.aborted === null ? "" : `; ABORTED: ${report.aborted}`)
  );
}

export function endStateLines(report: RunReport): string[] {
  const e = report.endState;
  if (e === null) return [];
  return [
    `  intents created: ${e.intentsAfter - e.intentsBefore} (#${e.intentsBefore} to #${e.intentsAfter - 1})`,
    `  committed spend: ${usd(e.committedBeforeCents)} to ${usd(e.committedAfterCents)} of ${usd(e.budgetCents)} budget`,
    `  paused: ${String(e.paused)}; roles unchanged: ${String(e.rolesUnchanged)}; rules unchanged: ${String(e.rulesUnchanged)}`,
    `  held intents from this run still waiting for the owner: ${e.heldIntentIds.length === 0 ? "none" : e.heldIntentIds.map((id) => `#${id}`).join(", ")}`,
  ];
}

// ------------------------------------------------------------------ Markdown

const cell = (text: string) => text.replace(/\|/g, "\\|").replace(/\n/g, " ");

export function markdown(report: RunReport): string {
  const s = summarize(report.attacks);
  const rules = report.rules;
  const out: string[] = [];
  out.push("# Red team report");
  out.push("");
  out.push(
    "<!-- Generated by `npm run redteam -- --contract production --markdown redteam/REPORT.md`. Do not edit by hand. -->",
  );
  out.push("");
  out.push(
    `Target: ${report.target === "self" ? "a self-contained devchain and MCP server" : "the running local stack"}, the \`${report.contract}\` Policy contract.`,
  );
  out.push(
    `Rules: budget ${usd(rules.budgetCents)}, max trade ${usd(rules.maxTradeCents)}, approval above ${usd(rules.approvalAboveCents)}, daily loss ${usd(rules.dailyLossCents)}, Crypto only.`,
  );
  out.push(
    `Result: ${report.attacks.length} attacks, ${s.held} held, ${s.bounded} bounded, ${s.breach} breaches, ${s.errors} errors, ${s.unexpected} unexpected.`,
  );
  out.push("");
  out.push("Verdicts:");
  out.push("");
  out.push("- `held`: the mandate, or the server in front of it, stopped the attempt.");
  out.push("- `bounded`: the attempt went through, but stayed inside the limit named in its row.");
  out.push("- `BREACH`: something that should be impossible happened.");
  out.push("");
  out.push("## Attacks");
  out.push("");
  out.push("| # | Attack | Surface | Tried | Expected | Actual | Verdict | Transactions |");
  out.push("| --- | --- | --- | --- | --- | --- | --- | --- |");
  report.attacks.forEach((r, i) => {
    const verdict = r.verdict === "bounded" && r.limit !== null ? `bounded: ${r.limit}` : r.verdict;
    const txs = r.txHashes.length === 0 ? "none" : r.txHashes.map((h) => `\`${shortHash(h)}\``).join(" ");
    out.push(
      `| ${i + 1} | ${cell(r.name)} (\`${r.id}\`) | ${r.surface} | ${cell(r.tried)} | ${cell(r.expected)} | ${cell(r.actual)} | ${cell(verdict)}${r.asExpected ? "" : " (UNEXPECTED)"} | ${txs} |`,
    );
  });
  out.push("");
  out.push("## Findings and limitations");
  out.push("");
  const findings = report.attacks.filter((r) => r.finding !== null);
  if (findings.length === 0) out.push("None.");
  for (const r of findings) out.push(`- \`${r.id}\`: ${r.finding ?? ""}`);
  out.push("");
  out.push("## Full transaction hashes");
  out.push("");
  for (const r of report.attacks.filter((a) => a.txHashes.length > 0)) {
    out.push(`- \`${r.id}\`: ${r.txHashes.map((h) => `\`${h}\``).join(", ")}`);
  }
  out.push("");
  return `${out.join("\n")}\n`.replace(/\n{3,}/g, "\n\n");
}
